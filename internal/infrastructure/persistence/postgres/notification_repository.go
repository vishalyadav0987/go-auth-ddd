// This method will also automatically maintain timestamps when a delivery is accepted or confirmed as delivered.

func (r *NotificationRepository) UpdateDeliveryStatus(
	ctx context.Context,
	deliveryID string,
	processingToken string,
	status domain.DeliveryStatus,
) error {
	if processingToken == "" {
		return fmt.Errorf("processing token is required")
	}

	if !status.IsValid() {
		return fmt.Errorf("invalid delivery status: %s", status)
	}

	result, err := r.db.ExecContext(
		ctx,
		`
        UPDATE notification_deliveries
SET status = $3,
    sent_at = CASE
        WHEN $3 = 'ACCEPTED' THEN NOW()
        ELSE sent_at
    END,
    delivered_at = CASE
        WHEN $3 = 'DELIVERED' THEN NOW()
        ELSE delivered_at
    END,
    processing_token = NULL,
    processing_started_at = NULL,
    updated_at = NOW()
WHERE id = $1
  AND status = 'PROCESSING'
  AND processing_token = $2
        `,
		deliveryID,
		processingToken,
		status,
	)
	if err != nil {
		return fmt.Errorf("update delivery status: %w", err)
	}

	rowsAffected, err := result.RowsAffected()
	if err != nil {
		return fmt.Errorf("get updated delivery rows: %w", err)
	}

	if rowsAffected == 0 {
		return fmt.Errorf(
			"delivery not found or processing ownership lost: %s",
			deliveryID,
		)
	}

	return nil
}

